// semverRe is the official SemVer 2.0.0 expression (https://semver.org).
var semverRe = regexp.MustCompile(`^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-((?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$`)

// checkManifest: SH-EXE-001 (hooks key), SH-NAM-001 (reserved name), SH-VER-001 (version, description).
func checkManifest(p pkg.Package, tree pkg.Tree) []pkg.Finding {
	var findings []pkg.Finding
	if file, ok := tree.File(pkg.ManifestPath); ok {
		var raw map[string]json.RawMessage
		if json.Unmarshal(file.Data, &raw) == nil {
			if _, hooks := raw["hooks"]; hooks {
				findings = append(findings, pkg.Finding{Code: pkg.CodeHooks, Path: pkg.ManifestPath,
					Message: "plugin.json must not declare hooks", Hint: "remove the hooks field; packages cannot run commands"})
			}
		}
	}
	m := p.Manifest
	if m.Name != "" && reservedName(m.Name) {
		findings = append(findings, pkg.Finding{Code: pkg.CodeReservedName, Path: pkg.ManifestPath,
			Message: fmt.Sprintf("plugin name %q is reserved or not kebab-case", m.Name),
			Hint:    "use kebab-case without '.' and without the words claude, anthropic or anthropics"})
	}
	if !semverRe.MatchString(m.Version) {
		findings = append(findings, pkg.Finding{Code: pkg.CodeVersion, Path: pkg.ManifestPath,
			Message: fmt.Sprintf("version %q is not SemVer", m.Version), Hint: "set version such as 1.0.0"})
	}
	if strings.TrimSpace(m.Description) == "" {
		findings = append(findings, pkg.Finding{Code: pkg.CodeVersion, Path: pkg.ManifestPath,
			Message: "description is required", Hint: "describe the plugin in one sentence"})
	}
	return findings
}

// reservedName follows the Claude Code plugin name check (code.claude.com/docs/en/plugins-reference,
// inspected 2026-10-21): errors and warnings both fail `claude plugin validate --strict`, so both
// are rejected here. A name with '.' is not kebab-case and also fails --strict.
func reservedName(name string) bool {
	if strings.Contains(name, ".") || strings.HasPrefix(name, "cc-plugin-") {
		return true
	}
	for _, word := range strings.Split(name, "-") {
		switch word {
		case "claude", "anthropic", "anthropics":
			return true
		}
	}
	return false
}

var slugRe = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)

// checkMCP: SH-SEC-001 (headers, env), SH-MCP-002 (stdio, command, args, cwd), SH-MCP-001 (outside the gateway).
// Shape errors of mcp.json are AP-003, reported by pkg.Parse.
func checkMCP(tree pkg.Tree, gatewayOrigin string) []pkg.Finding {
	file, ok := tree.File(pkg.MCPPath)
	if !ok {
		return nil
	}
	var doc struct {
		MCPServers map[string]map[string]json.RawMessage `json:"mcpServers"`
	}
	if json.Unmarshal(file.Data, &doc) != nil {
		return nil
	}
	var findings []pkg.Finding
	add := func(code, hint, format string, a ...any) {
		findings = append(findings, pkg.Finding{Code: code, Path: pkg.MCPPath, Message: fmt.Sprintf(format, a...), Hint: hint})
	}
	names := make([]string, 0, len(doc.MCPServers))
	for name := range doc.MCPServers {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		server := doc.MCPServers[name]
		for _, key := range []string{"headers", "env"} {
			if _, present := server[key]; present {
				add(pkg.CodeHeaders, "remove it; the generated layer adds the gateway token", "server %q must not declare %s", name, key)
			}
		}
		var typ, rawURL string
		_ = json.Unmarshal(server["type"], &typ)
		_, command := server["command"]
		if typ == "stdio" || command {
			add(pkg.CodeLocalMCP, "point the server at the Agent Gateway", "server %q runs a local command", name)
			continue
		}
		// pkg.Parse leaves these servers out of the model, so each field must be reported here.
		for _, key := range []string{"args", "cwd"} {
			if _, present := server[key]; present {
				add(pkg.CodeLocalMCP, "remove it; a remote server has only type and url", "server %q declares %s, which only a local command uses", name, key)
			}
		}
		_ = json.Unmarshal(server["url"], &rawURL)
		pattern := "^" + regexp.QuoteMeta(gatewayOrigin) + "/mcp/projects/[a-z0-9]+(-[a-z0-9]+)*/" + regexp.QuoteMeta(name) + "$"
		if typ != "streamable-http" || !slugRe.MatchString(name) || !regexp.MustCompile(pattern).MatchString(rawURL) {
			add(pkg.CodeNotGateway, fmt.Sprintf("use type streamable-http and url %s/mcp/projects/<project>/%s", gatewayOrigin, name),
				"server %q is not an Agent Gateway server", name)
		}
	}
	return findings
}

// checkLayout: every file is part of the core, or exactly a file generated by an adapter.
// SH-EXE-001 hooks, SH-EXE-002 bin/ and scripts/, SH-STR-002 stale generated file, SH-STR-001 anything else.
func checkLayout(p pkg.Package, tree pkg.Tree, modelComplete bool, adapters []converter.Adapter) []pkg.Finding {
	generated := map[string][][]byte{}
	if modelComplete {
		for _, a := range adapters {
			files, err := a.Convert(p)
			if err != nil {
				continue // a target that refuses the package is reported by `harness generate`
			}
			for _, f := range files {
				generated[f.Path] = append(generated[f.Path], f.Data)
			}
		}
	}
	var findings []pkg.Finding
	add := func(code, p, hint, msg string) {
		findings = append(findings, pkg.Finding{Code: code, Path: p, Message: msg, Hint: hint})
	}
	for _, f := range tree.Files {
		switch {
		case strings.ContainsAny(f.Path, `\:`): // pack and unpack refuse these paths
			add(pkg.CodeLayout, f.Path, "rename the file without '\\' or ':'", "path has a character that pack refuses")
		case f.Path == "hooks" || strings.HasPrefix(f.Path, "hooks/") || path.Base(f.Path) == "hooks.json":
			add(pkg.CodeHooks, f.Path, "remove it; packages cannot run commands", "hooks are not allowed")
		case strings.HasPrefix(f.Path, "bin/") || isSkillScript(f.Path):
			add(pkg.CodeExecutable, f.Path, "remove it; packages cannot ship executables", "executable directories are not allowed")
		case isCore(f.Path):
		case generated[f.Path] != nil:
			if !matchesAny(f.Data, generated[f.Path]) {
				add(pkg.CodeStale, f.Path, "run `harness generate` again", "generated file differs from the generator output")
			}
		case modelComplete:
			add(pkg.CodeLayout, f.Path, "keep only plugin.json, mcp.json, README.md, LICENSE, skills/<name>/ and dev.smartharness/agents/",
				"file is outside the package layout")
		}
	}
	return findings
}

func matchesAny(data []byte, candidates [][]byte) bool {
	for _, c := range candidates {
		if bytes.Equal(data, c) {
			return true
		}
	}
	return false
}

// isCore reports whether a path belongs to the authored core of a package.
func isCore(p string) bool {
	switch p {
	case pkg.ManifestPath, pkg.MCPPath, "README.md", "LICENSE":
		return true
	}
	if rest, ok := strings.CutPrefix(p, pkg.AgentsDir); ok {
		return !strings.Contains(rest, "/") && strings.HasSuffix(rest, pkg.AgentSuffix) && len(rest) > len(pkg.AgentSuffix)
	}
	parts := strings.SplitN(p, "/", 4)
	if len(parts) < 3 || parts[0] != "skills" {
		return false
	}
	return (len(parts) == 3 && parts[2] == "SKILL.md") ||
		(len(parts) == 4 && (parts[2] == "references" || parts[2] == "assets"))
}

func isSkillScript(p string) bool {
	parts := strings.SplitN(p, "/", 4)
	return len(parts) == 4 && parts[0] == "skills" && parts[2] == "scripts"
}

// Executable headers: shebang, ELF, Mach-O (both byte orders, 32/64-bit, universal), PE and WebAssembly.
var executableMagic = [][]byte{
	[]byte("#!"), []byte("\x7fELF"),
	{0xfe, 0xed, 0xfa, 0xce}, {0xfe, 0xed, 0xfa, 0xcf}, {0xce, 0xfa, 0xed, 0xfe}, {0xcf, 0xfa, 0xed, 0xfe}, {0xca, 0xfe, 0xba, 0xbe},
	[]byte("MZ"), []byte("\x00asm"),
}

// checkExecutable: SH-EXE-002 for an execute bit or an executable header.
func checkExecutable(f pkg.File, executableBit bool) []pkg.Finding {
	reason := ""
	if executableBit {
		reason = "file has an execute permission bit"
	}
	for _, magic := range executableMagic {
		if bytes.HasPrefix(f.Data, magic) {
			reason = "file starts with an executable header"
		}
	}
	if reason == "" {
		return nil
	}
	return []pkg.Finding{{Code: pkg.CodeExecutable, Path: f.Path, Message: reason, Hint: "packages cannot ship executables; remove the file or clear the execute bit"}}
}

// secretPatterns match credential shapes. Messages name the kind, never the matched text.
var secretPatterns = []struct {
	kind string
	re   *regexp.Regexp
}{
	{"GitHub token", regexp.MustCompile(`\bgh[pousr]_[A-Za-z0-9]{36,}`)},
	{"GitHub fine-grained token", regexp.MustCompile(`\bgithub_pat_[A-Za-z0-9_]{22,}`)},
	{"Anthropic API key", regexp.MustCompile(`\bsk-ant-[A-Za-z0-9_-]{20,}`)},
	{"OpenAI-style API key", regexp.MustCompile(`\bsk-[A-Za-z0-9_-]{20,}`)},
	{"Slack token", regexp.MustCompile(`\bxox[abpr]-[A-Za-z0-9-]{10,}`)},
	{"AWS access key", regexp.MustCompile(`\bAKIA[0-9A-Z]{16}\b`)},
	{"private key", regexp.MustCompile(`-----BEGIN [A-Z ]*PRIVATE KEY-----`)},
	{"JWT", regexp.MustCompile(`\beyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}`)},
	{"bearer token", regexp.MustCompile(`\bBearer [A-Za-z0-9._~+/=-]{20,}`)},
}

// Secrets reports SH-SEC-002, one finding per file and line. The converter conformance suite uses it too.
func Secrets(f pkg.File) []pkg.Finding {
	byLine := map[int]string{}
	for _, p := range secretPatterns {
		for _, loc := range p.re.FindAllIndex(f.Data, -1) {
			line := lineOf(f.Data, loc[0])
			if _, seen := byLine[line]; !seen {
				byLine[line] = p.kind
			}
		}
	}
	lines := make([]int, 0, len(byLine))
	for line := range byLine {
		lines = append(lines, line)
	}
	sort.Ints(lines)
	var findings []pkg.Finding
	for _, line := range lines {
		findings = append(findings, pkg.Finding{Code: pkg.CodeSecret, Path: f.Path, Line: line,
			Message: "text matches a credential pattern: " + byLine[line],
			Hint:    "remove the credential and revoke it; the gateway injects credentials"})
	}
	return findings
}
